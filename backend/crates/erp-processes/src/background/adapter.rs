//! 后台任务适配器契约：每种领域任务实现同一轮询入口。

use crate::Result;

/// 后台任务适配器。
///
/// 每种任务（导入、导出、同步等）各自实现领取与执行，执行器只负责按顺序调用，不感知领域细节。
#[async_trait::async_trait]
pub trait BackgroundTaskAdapter: Send + Sync {
    /// 返回任务名称。
    ///
    /// # 参数
    /// 无。
    ///
    /// # 返回
    /// 返回用于日志与指标的稳定任务名。
    fn name(&self) -> &'static str;

    /// 领取并执行一轮到期任务。
    ///
    /// # 参数
    /// 无。
    ///
    /// # 返回
    /// 返回本轮认领的任务数。
    ///
    /// # 错误
    /// 查询失败等不可恢复的轮询错误；单个任务的执行业务失败应由实现方内部消化并记明细，不得中断整轮。
    async fn run_due(&self) -> Result<usize>;
}
