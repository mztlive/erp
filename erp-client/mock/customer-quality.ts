function tag(
  type: BusinessTag["type"],
  code: string,
  tone: BusinessTag["tone"]
): BusinessTag {
  const catalog = TAG_RULE_CATALOG[type]
  return {
    type,
    code,
    label: catalog.labels[code as keyof typeof catalog.labels] ?? code,
    tone,
    ruleVersion: catalog.ruleVersion,
    explanation: catalog.explanation,
  }
}

