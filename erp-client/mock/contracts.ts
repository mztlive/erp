/** 新建销售单选择器：仅返回服务端判定可选的合同。 */
export function listContractsSelectableForNewSalesOrder(): ContractListRow[] {
  return MOCK_CONTRACT_LIST.filter((row) => {
    const center = MOCK_CONTRACT_CENTERS[row.contractId]
    if (center) return center.selectableForNewSalesOrder
    return (
      row.status === "EFFECTIVE" &&
      row.allowedActions.includes("CREATE_SALES_ORDER")
    )
  })
}
